    Key,

    /// <summary>Selects mouse button.</summary>
    MouseButton,

    /// <summary>Selects controller button.</summary>
    ControllerButton,

    /// <summary>Selects controller stick.</summary>
    ControllerStick,

    /// <summary>Selects controller trigger.</summary>
    ControllerTrigger,
}
