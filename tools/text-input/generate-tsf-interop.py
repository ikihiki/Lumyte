import re
from pathlib import Path
import argparse
parser = argparse.ArgumentParser(description="Generate source-generated COM ABI declarations from Win32 SDK headers.")
parser.add_argument("textstor", type=Path)
parser.add_argument("msctf", type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
headers=args.textstor.read_text()+'\n'+args.msctf.read_text()
interfaces={}
for m in re.finditer(r'MIDL_INTERFACE\("([^"]+)"\)\s*(\w+) : public (\w+)\s*\{(.*?)\n    \};',headers,re.S):interfaces[m[2]]=(m[1],m[3],m[4])
selected=['ITextStoreACP','ITextStoreACPSink','ITfThreadMgr','ITfDocumentMgr','ITfContextOwnerCompositionSink','ITfCompositionView','ITfRangeACP','ITfContext','ITfKeystrokeMgr','ITfContextOwnerCompositionServices','ITfUIElementMgr','ITfUIElementSink','ITfUIElement','ITfCandidateListUIElement','ITfCandidateListUIElementBehavior','ITfSource','ITfTextEditSink','ITfReadOnlyProperty','ITfProperty','IEnumTfRanges','ITfCategoryMgr','ITfDisplayAttributeMgr','ITfDisplayAttributeInfo']
structs={'TS_STATUS':'TsStatus','TS_SELECTION_ACP':'TsSelection','TS_RUNINFO':'TsRunInfo','TS_TEXTCHANGE':'TsTextChange','POINT':'TsfPoint','RECT':'TsfRect','TF_DISPLAYATTRIBUTE':'TfDisplayAttribute'}
scalars={'HRESULT':'int','DWORD':'uint','ULONG':'uint','UINT':'uint','LONG':'int','BOOL':'int','WCHAR':'char','TsViewCookie':'uint','TfEditCookie':'uint','TfClientId':'uint','TfGuidAtom':'uint','GUID':'Guid','CLSID':'Guid','IID':'Guid','TsLayoutCode':'int','TfShiftDir':'int','TfAnchor':'int','TfGravity':'int','WPARAM':'nuint','LPARAM':'nint','HWND':'nint','BSTR':'nint','LCID':'uint','LANGID':'ushort'}
def methods(name):
 guid,base,body=interfaces[name]
 result=[] if base=='IUnknown' else methods(base)
 body=re.sub(r'/\*.*?\*/','',body,flags=re.S)
 for method,args in re.findall(r'virtual HRESULT STDMETHODCALLTYPE (\w+)\((.*?)\) = 0;',body,re.S):
  args=re.sub(r'(?<![A-Za-z0-9])_[A-Za-z0-9]+[A-Za-z0-9_]*_(?:\([^)]*\))?','',args)
  # SAL tokens are annotations only, never ABI parameters.
  args=re.sub(r'\bconst\b','',args)
  vals=[]
  for arg in args.split(','):
   arg=' '.join(arg.split())
   if not arg or arg=='void':continue
   m=re.match(r'([A-Za-z_][A-Za-z_0-9]*)\s*(\**)([A-Za-z_][A-Za-z_0-9]*)$',arg)
   if not m:raise Exception((name,method,arg))
   typ,stars,pname=m.groups()
   if typ in ['REFGUID','REFIID','REFCLSID']:mapped='Guid*'
   elif typ in scalars:mapped=scalars[typ]+stars
   elif typ in structs:mapped=structs[typ]+stars
   elif stars:mapped='nint'+'*'*(len(stars)-1)
   else:mapped='int'
   vals.append(mapped+' @'+pname)
  result.append((method,vals))
 return result
base=root/'src/Platform/Lumyte.Platform.Windows.TextInput/Interop';base.mkdir(parents=True,exist_ok=True)
for name in selected:
 methods_list=methods(name);guid=interfaces[name][0]
 text='''// <auto-generated/>
// ABI declarations generated from Microsoft Win32 metadata TextStor.h/msctf.h.
// Inherited methods are flattened in native vtable order; HRESULTs are preserved.
using System;
using System.Runtime.InteropServices;
using System.Runtime.InteropServices.Marshalling;

namespace Lumyte.Platform.Windows.TextInput.Interop;

[GeneratedComInterface]
[Guid("'''+guid+'''")]
internal unsafe partial interface '''+name+'\n{\n'
 for method,vals in methods_list:text+='    [PreserveSig]\n    int '+method+'('+', '.join(vals)+');\n\n'
 text+='}\n';(base/(name+'.g.cs')).write_text(text)
